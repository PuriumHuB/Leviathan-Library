	local function G(stops, rotation)
		local t = {}
		for pos, clr in pairs(stops) do
			t[tostring(pos)] = { Color = Color3.fromHex(clr), Transparency = 0 }
		end
		return WindUI:Gradient(t, { Rotation = rotation or 45 })
	end

